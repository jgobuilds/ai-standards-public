#!/usr/bin/env python3
"""Generate per-tool adapter files from a repo's AGENTS.md.

`AGENTS.md` is the cross-vendor standard — Codex, Cursor, Copilot's coding
agent, Gemini CLI, Windsurf, Aider, Zed, Devin and Jules read it natively.
Claude Code is the notable exception: it reads CLAUDE.md and needs an explicit
import.

Rather than maintain one instruction file per tool (which drifts, silently, in
exactly the way our own build-vs-adopt lens forbids), this writes thin
**pointers** at each tool's expected path. One source of truth; N places that
reference it.

    python scripts/apply_adapters.py <repo>            # write adapters
    python scripts/apply_adapters.py <repo> --check    # verify, exit 1 on drift
    python scripts/apply_adapters.py <repo> --tools claude,copilot

A contributor clones the repo, their tool finds its own file, and needs to
install nothing. That is the whole point.
"""
import os, sys, argparse

SOURCE = "AGENTS.md"

# path -> (comment_style, why this path)
ADAPTERS = {
    "claude":   ("CLAUDE.md",                        "md",  "Claude Code"),
    "copilot":  (".github/copilot-instructions.md",  "md",  "GitHub Copilot"),
    "cursor":   (".cursor/rules/standards.mdc",      "mdc", "Cursor"),
    "windsurf": (".windsurfrules",                   "txt", "Windsurf"),
    "cline":    (".clinerules",                      "txt", "Cline"),
    "gemini":   ("GEMINI.md",                        "md",  "Gemini CLI"),
}

GENERATED = "<!-- generated by ai-standards/scripts/apply_adapters.py — edit AGENTS.md instead -->"


def body(kind, tool):
    """Claude Code supports @-imports, so its pointer is load-bearing. The rest
    have no import syntax, so theirs is an instruction to go read the file —
    which every one of these tools can act on, since they can all read files."""
    if kind == "claude":
        return (f"{GENERATED}\n\n"
                f"@{SOURCE}\n\n"
                f"## Claude Code\n\n"
                f"The instructions above are imported from `{SOURCE}`, the "
                f"cross-vendor source of truth for this repo. Add Claude-specific "
                f"guidance below this line, not in `{SOURCE}`.\n")
    if kind == "cursor":
        # .mdc files take YAML frontmatter; alwaysApply keeps it in context.
        return ("---\n"
                "description: Project standards (source of truth: AGENTS.md)\n"
                "alwaysApply: true\n"
                "---\n\n"
                f"{GENERATED}\n\n"
                f"Read `{SOURCE}` in the repository root and follow it. It is the "
                f"single source of truth for conventions, setup and constraints "
                f"in this project.\n")
    marker = GENERATED if kind != "txt" else "# generated by ai-standards — edit AGENTS.md instead"
    return (f"{marker}\n\n"
            f"Read `{SOURCE}` in the repository root and follow it. It is the "
            f"single source of truth for conventions, setup and constraints in "
            f"this project.\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("repo")
    ap.add_argument("--tools", default="all",
                    help="comma-separated: " + ",".join(ADAPTERS) + " (default all)")
    ap.add_argument("--check", action="store_true",
                    help="verify adapters exist and are current; exit 1 if not")
    a = ap.parse_args()

    root = os.path.abspath(a.repo)
    src = os.path.join(root, SOURCE)
    if not os.path.isfile(src):
        print(f"error: {SOURCE} not found in {root}", file=sys.stderr)
        print(f"       AGENTS.md is the source; adapters point at it. Write it first.",
              file=sys.stderr)
        return 2

    want = list(ADAPTERS) if a.tools == "all" else [t.strip() for t in a.tools.split(",")]
    unknown = [t for t in want if t not in ADAPTERS]
    if unknown:
        print(f"error: unknown tool(s): {', '.join(unknown)}", file=sys.stderr)
        return 2

    problems, wrote = [], []
    for tool in want:
        relpath, kind, label = ADAPTERS[tool]
        # comment style is carried per-adapter; 'kind' selects the body shape
        shape = tool if tool in ("claude", "cursor") else kind
        content = body(shape, label)
        dest = os.path.join(root, relpath)

        if a.check:
            if not os.path.isfile(dest):
                problems.append(f"{relpath}: missing ({label} would see nothing)")
                continue
            cur = open(dest, encoding="utf-8", errors="replace").read()
            if SOURCE not in cur:
                problems.append(f"{relpath}: no longer references {SOURCE} — "
                                f"looks like it has become a divergent copy")
            elif cur.strip() != content.strip():
                problems.append(f"{relpath}: out of date (regenerate)")
            continue

        os.makedirs(os.path.dirname(dest) or root, exist_ok=True)
        with open(dest, "w", encoding="utf-8", newline="\n") as f:
            f.write(content)
        wrote.append(f"{relpath}  ({label})")

    if a.check:
        if problems:
            print(f"Adapter check FAILED for {root}:")
            for p in problems:
                print(f"  - {p}")
            return 1
        print(f"Adapters current ({len(want)} tools) — all reference {SOURCE}.")
        return 0

    print(f"Wrote {len(wrote)} adapter(s) pointing at {SOURCE}:")
    for w in wrote:
        print(f"  {w}")
    print("\nEach is a pointer, not a copy — edit AGENTS.md and re-run.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
